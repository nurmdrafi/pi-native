const BASE='http://127.0.0.1:8787';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
const list=await(await fetch('http://127.0.0.1:9222/json/list')).json();
const page=list.find(t=>t.type==='page');
const ws=new WebSocket(page.webSocketDebuggerUrl);
await new Promise(r=>ws.onopen=r);
const pend=new Map();let id=0;
ws.onmessage=e=>{const d=JSON.parse(e.data);if(pend.has(d.id)){pend.get(d.id)(d.result);pend.delete(d.id);}};
const send=(method,params={})=>new Promise(r=>{const i=++id;pend.set(i,r);ws.send(JSON.stringify({id:i,method,params}));});
const sessions=await(await fetch(BASE+'/api/sessions')).json();
const cost=s=>s.costUsd??s.cost??s.totalCostUsd??s.total_cost_usd??0;
const arr=Array.isArray(sessions)?sessions:(sessions.sessions??[]);
const top=[...arr].sort((a,b)=>cost(b)-cost(a))[0];
const sid=top?(top.id??top.sessionId??top.session)??'':'';
await send('Page.enable');
await send('Page.navigate',{url:BASE+'/#/overview'});
await sleep(4000);
await send('Page.navigate',{url:BASE+'/#/sessions'});
await sleep(4000);
await send('Page.navigate',{url:BASE+'/#/sessions?session='+sid});
await sleep(5000);
await send('Runtime.evaluate',{expression:'window.scrollBy(0,900)'});
await sleep(3500);
await send('Runtime.evaluate',{expression:'window.scrollBy(0,-400)'});
await sleep(3500);
await send('Page.navigate',{url:BASE+'/#/overview'});
await sleep(3000);
ws.close();process.exit(0);
